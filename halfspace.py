def fix_docx(file_path, output_path):
    """Fix half-spaces in Word document while preserving formatting"""
    if not DOCX_AVAILABLE:
        raise Exception("ماژول python-docx نصب نیست. لطفاً با دستور زیر نصب کنید:\npip install python-docx")

    try:

        if not os.path.exists(file_path):
            raise Exception(f"فایل موجود نیست: {file_path}")

        if not os.access(file_path, os.R_OK):
            raise Exception(f"دسترسی خواندن فایل وجود ندارد: {file_path}")


        doc = Document(file_path)


        for para in doc.paragraphs:
            if para.text and para.text.strip():

                for run in para.runs:
                    if run.text and run.text.strip():
                        try:
                            original_text = run.text
                            processed_text = smart_half_space(run.text)
                            if original_text != processed_text:
                                run.text = processed_text
                        except Exception as e:
                            print(f"Error processing run text: {e}")
                            continue


        for table in doc.tables:
            for row in table.rows:
                for cell in row.cells:
                    for para in cell.paragraphs:
                        if para.text and para.text.strip():
                            for run in para.runs:
                                if run.text and run.text.strip():
                                    try:
                                        original_text = run.text
                                        processed_text = smart_half_space(run.text)
                                        if original_text != processed_text:
                                            run.text = processed_text
                                    except Exception as e:
                                        print(f"Error processing table cell text: {e}")
                                        continue


        for section in doc.sections:

            try:
                if section.header:
                    for para in section.header.paragraphs:
                        if para.text and para.text.strip():
                            for run in para.runs:
                                if run.text and run.text.strip():
                                    try:
                                        original_text = run.text
                                        processed_text = smart_half_space(run.text)
                                        if original_text != processed_text:
                                            run.text = processed_text
                                    except Exception as e:
                                        print(f"Error processing header text: {e}")
                                        continue
            except Exception as e:
                print(f"Error processing header: {e}")


            try:
                if section.footer:
                    for para in section.footer.paragraphs:
                        if para.text and para.text.strip():
                            for run in para.runs:
                                if run.text and run.text.strip():
                                    try:
                                        original_text = run.text
                                        processed_text = smart_half_space(run.text)
                                        if original_text != processed_text:
                                            run.text = processed_text
                                    except Exception as e:
                                        print(f"Error processing footer text: {e}")
                                        continue
            except Exception as e:
                print(f"Error processing footer: {e}")


        doc.save(output_path)
        return True

    except Exception as e:

        error_msg = f"خطا در پردازش فایل Word: {str(e)}"
        print(f"Full error traceback: {traceback.format_exc()}")
        raise Exception(error_msg)


def fix_xlsx(file_path, output_path):
    """Fix half-spaces in Excel file while preserving formatting"""
    if not XLSX_AVAILABLE:
        raise Exception("ماژول openpyxl نصب نیست. لطفاً با دستور زیر نصب کنید:\npip install openpyxl")

    try:

        if not os.path.exists(file_path):
            raise Exception(f"فایل موجود نیست: {file_path}")

        if not os.access(file_path, os.R_OK):
            raise Exception(f"دسترسی خواندن فایل وجود ندارد: {file_path}")


        wb = openpyxl.load_workbook(file_path)

        for sheet in wb.worksheets:
            for row in sheet.iter_rows():
                for cell in row:
                    if cell.value and isinstance(cell.value, str) and cell.value.strip():
                        try:

                            original_font = cell.font
                            original_alignment = cell.alignment
                            original_fill = cell.fill
                            original_border = cell.border
                            original_number_format = cell.number_format


                            original_text = cell.value
                            processed_text = smart_half_space(cell.value)

                            if original_text != processed_text:
                                cell.value = processed_text


                                cell.font = original_font
                                cell.alignment = original_alignment
                                cell.fill = original_fill
                                cell.border = original_border
                                cell.number_format = original_number_format
                        except Exception as e:
                            print(f"Error processing cell: {e}")
                            continue


        wb.save(output_path)
        return True

    except Exception as e:

        error_msg = f"خطا در پردازش فایل Excel: {str(e)}"
        print(f"Full error traceback: {traceback.format_exc()}")
        raise Exception(error_msg)


def choose_file():
    """Handle file selection and processing"""

    filetypes = []
    if DOCX_AVAILABLE:
        filetypes.append(("Word files", "*.docx"))
    if XLSX_AVAILABLE:
        filetypes.append(("Excel files", "*.xlsx"))

    if not filetypes:
        messagebox.showerror("خطا",
                             "هیچ ماژول پردازش فایل نصب نیست!\n\nبرای Word: pip install python-docx\nبرای Excel: pip install openpyxl")
        return

    filetypes.append(("All supported", "*.docx *.xlsx"))

    file_path = filedialog.askopenfilename(
        title="انتخاب فایل",
        filetypes=filetypes
    )

    if not file_path:
        return


    if not os.path.exists(file_path):
        messagebox.showerror("خطا", f"فایل موجود نیست:\n{file_path}")
        return

    filename, ext = os.path.splitext(file_path)
    output_path = filename + "_fixed" + ext


    if os.path.exists(output_path):
        result = messagebox.askyesno(
            "فایل موجود است",
            f"فایل خروجی از قبل موجود است:\n{output_path}\n\nآیا می‌خواهید آن را جایگزین کنید؟"
        )
        if not result:
            return


    output_dir = os.path.dirname(output_path)
    if not os.access(output_dir, os.W_OK):
        messagebox.showerror("خطا", f"دسترسی نوشتن در پوشه وجود ندارد:\n{output_dir}")
        return

    try:
        if ext.lower() == '.docx':
            if not DOCX_AVAILABLE:
                messagebox.showerror("خطا", "ماژول python-docx نصب نیست!\npip install python-docx")
                return
            fix_docx(file_path, output_path)
        elif ext.lower() == '.xlsx':
            if not XLSX_AVAILABLE:
                messagebox.showerror("خطا", "ماژول openpyxl نصب نیست!\npip install openpyxl")
                return
            fix_xlsx(file_path, output_path)
        else:
            messagebox.showerror("خطا ❌", "فقط فایل‌های .docx یا .xlsx پشتیبانی می‌شود.")
            return

        messagebox.showinfo("موفقیت ✅", f"فایل با موفقیت اصلاح شد و ذخیره شد:\n{output_path}")


        result = messagebox.askyesno("باز کردن پوشه", "آیا می‌خواهید پوشه خروجی را باز کنید؟")
        if result:
            try:
                import subprocess
                import platform
                if platform.system() == "Windows":
                    os.startfile(os.path.dirname(output_path))
                elif platform.system() == "Darwin":
                    subprocess.run(["open", os.path.dirname(output_path)])
                else:
                    subprocess.run(["xdg-open", os.path.dirname(output_path)])
            except Exception as e:
                print(f"نتوانستم پوشه را باز کنم: {os.path.dirname(output_path)}")
                print(f"Error: {e}")

    except Exception as e:
        error_msg = f"مشکلی پیش آمد:\n{str(e)}"
        print(f"Full error: {traceback.format_exc()}")
        messagebox.showerror("خطا ❌", error_msg)


